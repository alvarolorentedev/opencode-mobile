import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const tokens = JSON.parse(await readFile(new URL('shared/ui/theme/ui-tokens.json', root), 'utf8'));
const lines = ['/* Generated by npm run gen:ui-tokens. Edit ui-tokens.json. */', '@theme {'];
for (const [name, value] of Object.entries(tokens.shape)) lines.push(`  --radius-${name}: ${value}px;`);
for (const [name, value] of Object.entries(tokens.controls)) lines.push(`  --spacing-${name}: ${value}px;`);
for (const [name, value] of Object.entries(tokens.spacing)) lines.push(`  --spacing-${name}: ${value}px;`);
for (const [name, value] of Object.entries(tokens.typography)) {
  lines.push(`  --text-${name}: ${value.fontSize}px;`, `  --text-${name}--line-height: ${value.lineHeight}px;`);
}
lines.push('}', '@layer theme {', '  :root {');
for (const scheme of ['light', 'dark']) {
  lines.push(`    @variant ${scheme} {`);
  for (const [alias, role] of Object.entries(tokens.aliases)) lines.push(`      --color-${alias}: ${({ ...tokens.colors[scheme], ...tokens.presets.green[scheme] })[role]};`);
  lines.push('    }');
}
for (const platform of ['ios', 'android', 'web']) {
  lines.push(`    @variant ${platform} {`);
  for (const [role, value] of Object.entries(tokens.fonts[platform] ?? tokens.fonts.default)) lines.push(`      --font-${role}: ${value};`);
  lines.push('    }');
}
lines.push('  }', '}');
const output = `${lines.join('\n')}\n`;
const destination = new URL('shared/ui/theme/ui-tokens.generated.css', root);
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== output) throw new Error('UI tokens are stale. Run npm run gen:ui-tokens.');
} else await writeFile(destination, output);
